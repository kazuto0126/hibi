import type { ScenarioId } from './scenarios';

type Ex = [ja: string, zh: string];

function item(
  kind: CardKind,
  tag: ScenarioId,
  ja: string,
  meaning: string,
  ex?: Ex,
  jlpt?: JlptLevel,
  note?: string,
): SuggestedItem {
  return {
    kind,
    ja,
    meaning,
    example: ex ? { ja: ex[0], zh: ex[1] } : undefined,
    jlpt,
    note,
    tags: [tag],
  };
}
